// The major stock markets outside the US, as they really moved (rounded): year-end index levels
// where an index existed (Nikkei 225 from 1949, the FTSE 100 from 1984, DAX and CAC 40 from 1987,
// Hang Seng from 1969, Sensex and KOSPI from 1979, TAIEX from 1984, Shanghai from 1990, the JSE
// from 1994...), MSCI-style dollar returns for markets whose local prices were wrecked by
// hyperinflation (Brazil, Mexico, Argentina, Turkey, Russia's RTS), long-run real-return
// reconstructions for the decades before (Dimson-Marsh-Staunton style), plus local consumer
// inflation, policy rates and the big housing booms and busts. Before a country's first segment
// the series comes from history/markets.ts's calibrated proxy (world factor + local events).

/** One stretch of a country's equity history. */
export interface EquitySegment {
  /** First year covered (for 'level' and 'usdLevel', the base year: returns start the year after). */
  from: number
  /**
   * 'real': real total returns (%). 'nominal': local nominal total returns (%). 'usd': US-dollar
   * total returns (%), deflated by US inflation. 'level': year-end local price-index levels
   * (dividends added from `dividend`). 'usdLevel': year-end index levels quoted in dollars.
   */
  kind: 'real' | 'nominal' | 'usd' | 'level' | 'usdLevel'
  values: readonly number[]
  /** Dividend yield (%) for level series: a constant or (year, %) anchors. */
  dividend?: number | readonly (readonly [number, number])[]
}

export interface CountryHistory {
  equity: readonly EquitySegment[]
  /** Consumer inflation (%), one value per year from `from`. */
  inflation: readonly { from: number; values: readonly number[] }[]
  /** Before its own inflation data starts, borrow this country's (e.g. Canada → the US). */
  inflationLike?: string
  /** Policy-rate anchors (year, %): each holds until the next one. */
  rates: readonly (readonly [number, number])[]
  /** Real house-price changes (%) in the years that matter. */
  housing?: Readonly<Record<number, number>>
}

function rep(v: number, n: number): number[] {
  return Array.from({ length: n }, () => v)
}

/** The same value for every year of a span (inclusive). */
function span(from: number, to: number, v: number): Record<number, number> {
  const out: Record<number, number> = {}
  for (let y = from; y <= to; y++) out[y] = v
  return out
}

