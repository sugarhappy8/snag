export interface CurrencyDef {
  /** ISO 4217 code where there is one (old currencies use their historic code). */
  code: string
  /** e.g. 'Japanese yen', 'Deutsche Mark'. */
  name: string
  /** e.g. '¥', 'DM', 'Rp'. */
  symbol: string
  /** Written after the number: '100 kr'. */
  suffix?: boolean
  /** A space after a symbol in front: 'CHF 100', 'Rp 5,000'. */
  space?: boolean
  /** Digits after the decimal point in everyday use (0: yen, won, rupiah, lira...). Default 2. */
  decimals?: number
}

/** An older currency, used in the years before `until`. */
interface Era {
  until: number
  cur: CurrencyDef
  /** How many units of it made one unit of the next currency when it was replaced. */
  per: number
}

interface CountryMoney {
  /** Today's currency. */
  cur: CurrencyDef
  /** Units of it per US dollar in PRESENT_YEAR. */
  fx: number
  /** Older currencies, oldest first. */
  eras?: Era[]
  /** Local inflation by period: [fromYear, yearly rate] (null = like the US), in year order. */
  infl?: [number, number | null][]
}

type CurOpts = Pick<CurrencyDef, 'suffix' | 'space' | 'decimals'>

function cur(code: string, name: string, symbol: string, opts: CurOpts = {}): CurrencyDef {
  return { code, name, symbol, ...opts }
}

/** r(1950, 0.04, 1960, 0.03) → [[1950, 0.04], [1960, 0.03]]. */
function r(...pairs: (number | null)[]): [number, number | null][] {
  const out: [number, number | null][] = []
  for (let i = 0; i + 1 < pairs.length; i += 2) out.push([pairs[i] as number, pairs[i + 1]])
  return out
}

function era(until: number, c: CurrencyDef, per = 1): Era {
  return { until, cur: c, per }
}

