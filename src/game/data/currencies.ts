// Local currencies, then and now: what money is called, what it looks like and what it was worth.
//
// The engine keeps every amount in constant PRESENT_YEAR US dollars (history/timeline.ts). This
// module turns that into what the player should see (core.ts showMoney/formatMoney):
//
// - "Local currency": a Japanese life earns yen and an Indonesian one rupiah, at today's exchange
//   rate (`fx`, units per US dollar in PRESENT_YEAR).
// - "Prices as they were": the year's own money. A 1980 Japanese salary is shown in 1980 yen,
//   deflated with Japan's own inflation (not the US price level times the 1980 exchange rate,
//   which would make 1980 yen look far too small: the yen was undervalued then), and before a
//   currency change it is shown in the old money (Deutsche Mark until 2002, cruzeiros in 1985
//   Brazil, Soviet rubles in 1975 Moscow...). In US-dollar mode it is the US price level of the
//   year (1980 → about a quarter of today's dollars).
//
// display = internal × unitsPerDollar(country, year), where for "prices as they were"
//   unitsPerDollar(c, PRESENT_YEAR) = fx and, going back a year at a time,
//   unitsPerDollar(c, y - 1) = unitsPerDollar(c, y) / (1 + inflation(c, y)) × (old units per new unit
//   when the currency changed in year y).
// Inflation comes from `infl` (local yearly rates by period, rough decade averages with the big
// episodes spelled out); years without data follow US inflation. After PRESENT_YEAR every
// country inflates like the US (timeline.ts FUTURE_INFLATION), in today's currency.
//
// Figures are rounded approximations for a game, not financial data. Hyperinflations are kept
// (Weimar 1923, Hungary 1946, Brazil 1993, Zimbabwe 2008, Venezuela 2018): a 1946 Budapest life
// really did see prices in the octillions of pengő.
