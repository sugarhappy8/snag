const FALLBACK: CountryMoney = { cur: USD, fx: 1 }

function moneyOf(countryId: string): CountryMoney {
  return DATA[countryId] ?? FALLBACK
}

/** True when the country has currency data (every world.ts country does). */
export function hasCurrencyData(countryId: string): boolean {
  return countryId in DATA
}

/** The currency a country uses today. */
export function presentCurrency(countryId: string): CurrencyDef {
  return moneyOf(countryId).cur
}

/** The currency in use in a country in a given year (the Deutsche Mark in 1990 Germany). */
export function currencyOf(countryId: string, year: number = PRESENT_YEAR): CurrencyDef {
  const m = moneyOf(countryId)
  for (const e of m.eras ?? []) if (year < e.until) return e.cur
  return m.cur
}

/**
 * When a country switched currency in `year` (the euro in Germany, 2002): what was replaced, what
 * replaced it and how many old units made one new one. null in other years.
 */
export function currencyChangeAt(countryId: string, year: number): { from: CurrencyDef; to: CurrencyDef; per: number } | null {
  const eras = moneyOf(countryId).eras ?? []
  for (let i = 0; i < eras.length; i++) {
    const e = eras[i]
    if (e.until !== year) continue
    const to = i + 1 < eras.length ? eras[i + 1].cur : moneyOf(countryId).cur
    // Only a new symbol (₹ in 2010, ₽ in 2014) is not a currency change.
    if (e.cur.code === to.code && e.per === 1 && e.cur.name === to.name) return null
    return { from: e.cur, to, per: e.per }
  }
  return null
}

/** Inflation in `year` (prices that year vs the year before). `infl` is sorted by year. */
function rateIn(infl: readonly [number, number | null][], year: number): number {
  let rate: number | null = null
  for (const [from, v] of infl) {
    if (from > year) break
    rate = v
  }
  const r0 = rate ?? usInflation(year)
  // Guard against typos: deflation beyond -50% a year never happened.
  return Number.isFinite(r0) ? Math.max(-0.5, r0) : 0
}

const cache = new Map<string, number[]>()

/** units[y - HISTORY_START]: display units of the year's currency per internal dollar, prices of the year. */
function unitsTable(countryId: string): number[] {
  const hit = cache.get(countryId)
  if (hit) return hit
  const m = moneyOf(countryId)
  const n = PRESENT_YEAR - HISTORY_START + 1
  const out = new Array<number>(n)
  out[n - 1] = m.fx
  const perAt = new Map<number, number>()
  for (const e of m.eras ?? []) perAt.set(e.until, (perAt.get(e.until) ?? 1) * e.per)
  // Stable sort: when two entries share a year, the later one (an override) wins.
  const infl = (m.infl ?? []).map((x, i) => [x, i] as const).sort((a, b) => a[0][0] - b[0][0] || a[1] - b[1]).map(([x]) => x)
  for (let y = PRESENT_YEAR; y > HISTORY_START; y--) {
    const i = y - HISTORY_START
    out[i - 1] = (out[i] / (1 + rateIn(infl, y))) * (perAt.get(y) ?? 1)
  }
  cache.set(countryId, out)
  return out
}

/**
 * Display units per internal (PRESENT_YEAR US) dollar. nominal: in the money of that year (its
 * currency and prices); otherwise today's currency at today's rate.
 */
export function unitsPerDollar(countryId: string, year: number, nominal = true): number {
  const m = moneyOf(countryId)
  if (!nominal) return m.fx
  if (!Number.isFinite(year)) return m.fx
  const y = Math.round(year)
  if (y >= PRESENT_YEAR) return m.fx * priceLevel(y)
  return unitsTable(countryId)[Math.max(HISTORY_START, y) - HISTORY_START]
}

/**
 * Units of the year's currency per US dollar of that year (purchasing-power based): 1980 Japan →
 * about 380 yen. Flavor for exchange-rate talk; prices themselves use unitsPerDollar.
 */
export function exchangeRate(countryId: string, year: number = PRESENT_YEAR): number {
  return unitsPerDollar(countryId, year) / priceLevel(Math.min(PRESENT_YEAR, Math.max(HISTORY_START, year)))
}

